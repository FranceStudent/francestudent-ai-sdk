import {
	ReasoningEffort,
	SafetyAppealSignal,
	SharePermission,
	WebSearchFilterType,
	WebSearchMode,
} from '../../enums/Data';

/**
 * Options specifying the data that is to be posted.
 *
 * @public
 */
export interface IPostArgs {
	/** The ID of the target resource (chat, project, file, skill, MCP server, session, ...). */
	id?: string;

	/** The ID of the target chat, when it is not the main target. */
	chatId?: string;

	/** The ID of the target message. */
	messageId?: string;

	/** The ID of the target user. */
	userId?: number;

	/** The new chat to create. */
	chat?: INewChat;

	/** The message to send to an existing chat. */
	message?: INewMessage;

	/** The text content (edited message, ...). */
	content?: string;

	/** The updates to apply to a chat. */
	chatUpdates?: IChatUpdates;

	/** The name of the project to create. */
	name?: string;

	/** The updates to apply to a project. */
	projectUpdates?: IProjectUpdates;

	/** The share to add, update or remove. */
	share?: IShareTarget;

	/** Whether the message is upvoted (`true`), downvoted (`false`). */
	isUpvoted?: boolean;

	/** The shared conversation to import. */
	conversationImport?: IConversationImportOptions;

	/** The email address (invitation, ...). */
	email?: string;

	/** The updates to apply to the user settings. */
	userUpdates?: IUserUpdates;

	/** The updates to apply to the public profile. */
	profileUpdates?: IProfileUpdates;

	/** The updates to apply to the personalization (custom instructions, ...). */
	instructions?: IInstructionsUpdates;

	/** The notification preferences to set. */
	notificationPreferences?: INotificationPreferences;

	/** The web search domain filter to set. */
	webSearchDomains?: IWebSearchDomains;

	/** The safety appeal to submit. */
	appeal?: ISafetyAppeal;

	/** The MCP server to create. */
	mcpServer?: INewMcpServer;

	/** The updates to apply to an MCP server. */
	mcpServerUpdates?: IMcpServerUpdates;

	/** The OAuth callback parameters of an MCP server authorization. */
	oauth?: IOAuthCallback;

	/** The file to upload. */
	upload?: IUpload;

	/** The files to upload. */
	uploads?: IUpload[];

	/** The expiration policy of an uploaded file. */
	expiresAfter?: IFileExpiration;

	/** The flags to set. */
	flags?: string[];

	/** Whether the target becomes the default (skill version, ...). */
	isDefault?: boolean;

	/** The version of the target skill. */
	version?: string;
}

/**
 * The details of a new chat.
 *
 * @public
 */
export interface INewChat {
	/** The ID of the agent (model) to chat with. */
	agentId: number;

	/** The first message. */
	content: string;

	/** The ID to give to the chat. Generated by the server if not set. */
	chatId?: string;

	/** The IDs of uploaded images to attach. */
	images?: string[];

	/** The IDs of uploaded files (v2) to attach. */
	files?: string[];

	/** Whether to enable web search. */
	enableWebSearch?: boolean;

	/** The ID of the project to create the chat in. */
	projectId?: string;

	/** Whether the chat is private. */
	isPrivate?: boolean;

	/** Whether the chat is incognito (not saved in history). */
	isIncognito?: boolean;

	/** Whether to enable the canvas. */
	enableCanvas?: boolean;
}

/**
 * The details of a message sent to an existing chat.
 *
 * @public
 */
export interface INewMessage {
	/** The text of the message. */
	content: string;

	/** The ID of the agent (model) to answer with. Defaults to the agent of the chat. */
	agentId?: number;

	/** The IDs of uploaded images to attach. */
	images?: string[];

	/** The IDs of uploaded files (v2) to attach. */
	files?: string[];

	/** Whether to enable web search. */
	enableWebSearch?: boolean;
}

/**
 * The updates to apply to a chat.
 *
 * @public
 */
export interface IChatUpdates {
	title?: string;
	isPrivate?: boolean;
}

/**
 * The updates to apply to a project.
 *
 * @public
 */
export interface IProjectUpdates {
	name?: string;
	flags?: number;
}

/**
 * The target (and permission) of a share. Either `userId` or `userEmail` must be set.
 *
 * @public
 */
export interface IShareTarget {
	userId?: number;
	userEmail?: string;
	permission?: SharePermission;
}

/**
 * The shared conversation to import.
 *
 * @public
 */
export interface IConversationImportOptions {
	/** The share link of the conversation. */
	link: string;

	/** The local model to continue the conversation with. */
	model: string;
}

/**
 * The updates to apply to the user settings.
 *
 * @public
 */
export interface IUserUpdates {
	name?: string;
	pets?: string;
	theme?: string;
	language?: 'en' | 'fr';
	speechToTextLanguage?: 'en' | 'fr';
	lastChangelogViewedAt?: string;
	flags?: number;
}

/**
 * The updates to apply to the public profile.
 *
 * @public
 */
export interface IProfileUpdates {
	name?: string;
	avatar?: string;
}

/**
 * The updates to apply to the personalization settings.
 *
 * @public
 */
export interface IInstructionsUpdates {
	gptReasoning?: ReasoningEffort;
	customInstructions?: string;
	defaultModelId?: number;
	adsFrequency?: string;
	memoryEnabled?: boolean;
	imageGenerationModel?: string;
	webSearchMode?: WebSearchMode;
	documentToolsEnabled?: boolean;
	imageGenerationToolEnabled?: boolean;
}

/**
 * The notification preferences.
 *
 * @public
 */
export interface INotificationPreferences {
	appUpdates?: boolean;
	offersAndSubscriptions?: boolean;
}

/**
 * The web search domain filter.
 *
 * @public
 */
export interface IWebSearchDomains {
	filterType: WebSearchFilterType;
	allowedDomains: string[];
	blockedDomains: string[];
}

/**
 * A safety classification appeal.
 *
 * @public
 */
export interface ISafetyAppeal {
	signal: SafetyAppealSignal;
	userInput?: string;
}

/**
 * The details of a new MCP server.
 *
 * @public
 */
export interface INewMcpServer {
	label: string;
	url: string;
	description?: string;
	authType?: string;
	oauthScopes?: string[];
	allowedTools?: string[];
	requireApproval?: string;
	deferLoading?: boolean;
	enabled?: boolean;
	authorization?: string;
	headers?: Record<string, string>;
}

/**
 * The updates to apply to an MCP server.
 *
 * @public
 */
export interface IMcpServerUpdates extends Partial<INewMcpServer> {
	clearAuthorization?: boolean;
	clearHeaders?: boolean;
}

/**
 * The parameters received on the OAuth callback.
 *
 * @public
 */
export interface IOAuthCallback {
	code: string;
	state: string;
}

/**
 * A file to upload.
 *
 * @public
 */
export interface IUpload {
	/** The content of the file. */
	data: Blob | Uint8Array;

	/** The name of the file. */
	name: string;

	/** The MIME type of the file. */
	type?: string;
}

/**
 * The expiration policy of an uploaded file.
 *
 * @public
 */
export interface IFileExpiration {
	anchor: string;
	seconds: number;
}
